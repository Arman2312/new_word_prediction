def clean_text(text):

    text = text.lower()

    text = re.sub(r"[^a-z0-9\s']", " ", text)

    # Clean extra spaces without removing line breaks
    text = re.sub(r"[ \t]+", " ", text)

    # Clean each line
    lines = [
        line.strip()
        for line in text.splitlines()
        if line.strip()
    ]

    return "\n".join(lines)



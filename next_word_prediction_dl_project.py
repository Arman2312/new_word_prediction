def predict_next_words(input_text, top_k=5):

    if not input_text.strip():
        return []

    # Convert input to lowercase
    input_text = input_text.lower()

    # Convert words into tokens
    tokens = tokenizer.texts_to_sequences(
        [input_text]
    )[0]

    if not tokens:
        return []

    # Keep only the latest context
    tokens = tokens[-INPUT_LEN:]

    # Apply padding
    padded = pad_sequences(
        [tokens],
        maxlen=INPUT_LEN,
        padding="pre"
    )

    # Predict probabilities
    predictions = model.predict(
        padded,
        verbose=0
    )[0]

    # Ignore padding and unknown-word predictions
    predictions[0] = 0

    if tokenizer.oov_token:
        oov_id = tokenizer.word_index[tokenizer.oov_token]
        predictions[oov_id] = 0

    # Get top predictions
    top_indices = np.argsort(predictions)[-top_k:][::-1]

    results = []

    for index in top_indices:

        word = tokenizer.index_word.get(index)

        if word is not None:

            probability = predictions[index] * 100

            results.append({
                "word": word,
                "probability": round(float(probability), 2)
            })

    return results

def generate_prediction(input_text):

    results = predict_next_words(input_text)

    if not results:
        return "Please enter a valid sentence."

    output = "### Next Word Predictions\n\n"

    for i, item in enumerate(results, start=1):

        output += (
            f"**{i}. {item['word']}**"
            f" — {item['probability']}%\n\n"
        )

    return output



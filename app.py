import gradio as gr
import tensorflow as tf
import numpy as np
import pickle
import re

from tensorflow.keras.preprocessing.sequence import pad_sequences

# Project settings
INPUT_LEN = 19

# Load trained model
model = tf.keras.models.load_model("next_word_model.keras")

# Load tokenizer
with open("tokenizer.pkl", "rb") as file:
    tokenizer = pickle.load(file)


# Next word prediction function
def predict_next_word(text):

    if not text.strip():
        return "Please enter some text first."

    # Apply the same preprocessing used during training
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s']", "", text)

    # Convert text into token IDs
    tokens = tokenizer.texts_to_sequences([text])[0]

    if not tokens:
        return "No recognized words found. Please enter another sentence."

    # Keep only the last 19 tokens
    tokens = tokens[-INPUT_LEN:]

    # Apply padding
    padded = pad_sequences(
        [tokens],
        maxlen=INPUT_LEN,
        padding="pre"
    )

    # Predict probabilities
    predictions = model.predict(padded, verbose=0)[0]

    # Get token IDs to exclude
    excluded_ids = {0}

    oov_id = tokenizer.word_index.get("<OOV>")
    if oov_id is not None:
        excluded_ids.add(oov_id)

    # Find top 5 predictions
    ranked_ids = np.argsort(predictions)[::-1]

    results = []

    for token_id in ranked_ids:
        if token_id in excluded_ids:
            continue

        word = tokenizer.index_word.get(int(token_id))

        if word is None:
            continue

        probability = float(predictions[token_id]) * 100

        results.append(
            f"{len(results) + 1}. **{word}** — {probability:.2f}%"
        )

        if len(results) == 5:
            break

    if not results:
        return "No predictions available."

    return "\n\n".join(results)


# Create application interface
with gr.Blocks() as demo:

    gr.Markdown("# Next Word Prediction System")

    gr.Markdown(
        "Enter a sentence and let the LSTM model "
        "predict the next possible words."
    )

    input_text = gr.Textbox(
        label="Enter your sentence",
        placeholder="I am learning artificial...",
        lines=3
    )

    predict_button = gr.Button("Predict Next Word")

    output = gr.Markdown(label="Predictions")

    predict_button.click(
        fn=predict_next_word,
        inputs=input_text,
        outputs=output
    )

    gr.ClearButton(
        components=[input_text, output]
    )

# Launch application
demo.launch()